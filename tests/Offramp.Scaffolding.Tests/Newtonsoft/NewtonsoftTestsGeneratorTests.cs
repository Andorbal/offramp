    [Theory]
    [InlineData("newtonsoft-sdk")]
    [InlineData("newtonsoft-legacy")]
    [ProducesDiagnostic("OFR3731")]
    [ProducesDiagnostic("OFR3732")]
    [ProducesDiagnostic("OFR3737")]
    public async Task Generation_matches_the_snapshot(string fixture)
    {
        var scanned = await ScannedFixtures.GetAsync(fixture);
        var (result, changeSet, diagnostics) = Generate(scanned);

        var text = new StringBuilder(OfframpJson.Serialize(result with { Preview = null }, ScaffoldingJsonContext.Default.NewtonsoftTestsResult)).Append('\n');
        foreach (var d in diagnostics.ToSortedList())
        {
            text.Append(d.Code).Append(' ').Append(d.Project).Append(' ').Append(d.Message).Append('\n');
        }

        foreach (var create in changeSet!.Creates.Where(c => !c.Path.EndsWith("OfframpProbe.cs", StringComparison.Ordinal) && !c.Path.EndsWith("OfframpObjectDump.cs", StringComparison.Ordinal)))
        {
            text.Append("=== ").Append(create.Path).Append('\n').Append(Encoding.UTF8.GetString(create.Content));
        }

        foreach (var edit in changeSet.Edits)
        {
            text.Append("=== edit ").Append(edit.Path).Append('\n');
        }

        await Verify(text.ToString(), extension: "txt").UseParameters(fixture);
    }

    [Fact]
    public async Task A_second_run_over_the_written_probes_changes_nothing()
    {
        var scanned = await ScannedFixtures.ScanAsync("newtonsoft-legacy");
        var (_, first, _) = Generate(scanned);
        Write(scanned.Root, first!);

        var (result, second, _) = Generate(scanned);

        Assert.Null(second);
        Assert.All(result.Files, f => Assert.Equal("unchanged", f.Action));
    }

    [Fact]
    [ProducesDiagnostic("OFR3742")]
    public async Task A_file_without_the_header_is_the_users_and_is_left_alone()
    {
        var scanned = await ScannedFixtures.ScanAsync("newtonsoft-sdk");
        var path = "tests/Catalog.Tests/NewtonsoftCharacterization/CatalogSerializeProbes.cs";
        Directory.CreateDirectory(Path.Combine(scanned.Root, Path.GetDirectoryName(path)!));
        File.WriteAllText(Path.Combine(scanned.Root, path), "// Mine now.\n");

        var (result, changeSet, diagnostics) = Generate(scanned);

        Assert.Contains(result.Files, f => f.Path == path && f.Action == "kept");
        Assert.DoesNotContain(changeSet!.Creates.Concat<object>(changeSet.Edits).Concat(changeSet.Deletes), c => c.ToString()!.Contains(path, StringComparison.Ordinal));
        Assert.DoesNotContain(result.Probes, p => p.File == path);
        Assert.Contains(diagnostics.ToSortedList(), d => d.Code == "OFR3742" && d.File == path);
    }

    [Fact]
