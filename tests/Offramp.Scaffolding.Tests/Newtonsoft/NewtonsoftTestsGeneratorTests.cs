    [Fact]
    [ProducesDiagnostic("OFR3734")]
    public async Task Two_test_projects_for_one_production_project_need_a_choice()
    {
        var scanned = await ScannedFixtures.GetAsync("newtonsoft-sdk");
        var model = scanned.Outcome.Model!;
        var tests = model.Projects.Single(p => p.Id == CatalogTests);
        var renamed = model with
        {
            Projects = [.. model.Projects.Where(p => p.Id != CatalogTests),
                tests with { Name = "CatalogSpecs" },
                tests with { Id = "tests/Catalog.Checks/Catalog.Checks.csproj", Name = "CatalogChecks" }],
        };

        var (ambiguous, _, diagnostics) = Generate(scanned, r => r with { Model = renamed });
        var (chosen, _, _) = Generate(scanned, r => r with { Model = renamed, TestProjects = new Dictionary<string, string> { ["Catalog"] = "CatalogSpecs" } });

        Assert.DoesNotContain(ambiguous.Targets, t => t.Production == Catalog);
        Assert.Contains(diagnostics.ToSortedList(), d => d.Code == "OFR3734" && d.Message.Contains("Catalog.Checks", StringComparison.Ordinal));
        Assert.Equal("config", chosen.Targets.Single(t => t.Production == Catalog).By);
    }

