namespace Offramp.Scaffolding.Newtonsoft;

public sealed record NewtonsoftTestsRequest
{
    public required string RepositoryRoot { get; init; }

    public required WorkspaceModel Model { get; init; }

    /// <summary>Production project ids; empty for every project with sites.</summary>
    public IReadOnlyList<string> Projects { get; init; } = [];

    /// <summary>The test project for a single production project (<c>--to</c>), by id.</summary>
    public string? To { get; init; }

    /// <summary><c>newtonsoft.tests.projects</c>: production project (id or name) to test project (id or name).</summary>
    public IReadOnlyDictionary<string, string> TestProjects { get; init; } = new Dictionary<string, string>();

    /// <summary>An absolute folder of real payloads, or null.</summary>
    public string? Samples { get; init; }

    public string Folder { get; init; } = "NewtonsoftCharacterization";

    public int SamplesPerType { get; init; } = 3;

    public int ObjectDepth { get; init; } = 3;

    public int EntryDepth { get; init; } = 4;

    public IReadOnlyList<string> NonHermetic { get; init; } = [];

    public required DiagnosticBag Diagnostics { get; init; }

    public IProgressSink Progress { get; init; } = NullProgressSink.Instance;

    /// <summary>Where compilations come from; null for the recorded compiler logs.</summary>
    public ICompilationSource? Compilations { get; init; }
}

/// <summary>
/// <c>offramp newtonsoft tests</c>' generation (docs/spec/commands/newtonsoft.md#newtonsoft-tests;
/// ADR 0071): probes into the test projects that cover each production project, compiled into the
/// test project's recorded compilation before anything is written, as one change set.
/// </summary>
public static class NewtonsoftTestsGenerator
{
    private const string Header = "// <auto-generated>\n//   Written by `offramp newtonsoft tests`";
    private const string Category = "NewtonsoftCharacterization";

    public static (NewtonsoftTestsResult Result, ChangeSet? ChangeSet) Generate(NewtonsoftTestsRequest request, CancellationToken cancellationToken = default)
    {
        using var owned = request.Compilations is null ? new CompilationLoader(request.RepositoryRoot) : null;
        var compilations = request.Compilations ?? owned!;
        // The scan's own findings are `newtonsoft scan`'s to report.
        NewtonsoftScanner.Scan(new NewtonsoftScanRequest
        {
            RepositoryRoot = request.RepositoryRoot,
            Model = request.Model,
            Target = NewtonsoftRules.Measured,
            Diagnostics = new DiagnosticBag(),
            Progress = request.Progress,
            Compilations = compilations,
            EntryDepth = request.EntryDepth,
            NonHermetic = request.NonHermetic,
        }, out var scanned, cancellationToken);

        var productions = scanned
            .Where(s => !IsTest(s.Project) && s.Sites.Count > 0 && (request.Projects.Count == 0 || request.Projects.Contains(s.Project.Id, StringComparer.Ordinal)))
            .OrderBy(s => s.Project.Id, StringComparer.Ordinal)
            .ToList();
        var samples = Samples(request, scanned);
        var targets = new List<ProbeTarget>();
        var planned = new List<(ProbeTarget Target, ProbePlanner Planner, ScannedProject Production)>();
        foreach (var production in productions)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (Target(request, production.Project, productions.Count) is not { } target)
            {
                continue;
            }

            var test = request.Model.Projects.Single(p => p.Id == target.TestProject);
            var testCompilation = CompilationLoader.PreferredTarget(test) is { } tfm ? compilations.LoadForProject(test, tfm) : null;
            var planner = new ProbePlanner(production, test, testCompilation, request.Model, compilations, samples, request.SamplesPerType, request.ObjectDepth,
                target.Folder + "/" + ClassName(production.Project) + "SerializeProbes.cs", target.Folder + "/" + ClassName(production.Project) + "DeserializeProbes.cs");
            planner.Plan();
            if (!planner.TypeProbesAllowed && production.Sites.Any(s => s.Site.EntryPoint is null))
            {
                request.Diagnostics.Report(DiagnosticCatalog.OFR3743,
                    $"{test.Id} does not compile against {production.Project.Id}'s Newtonsoft.Json {production.Reference.Version}; only entry probes are generated for it.",
                    new DiagnosticLocation(test.Id));
            }

            targets.Add(target);
            planned.Add((target, planner, production));
        }

        var changeSet = new ChangeSet();
        var files = new List<GeneratedFile>();
        var probes = new List<PlannedProbe>();
        var uncovered = planned.SelectMany(p => p.Planner.Uncovered).ToList();
        foreach (var group in planned.GroupBy(p => p.Target.TestProject).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var test = request.Model.Projects.Single(p => p.Id == group.Key);
            var folder = group.First().Target.Folder;
            var kept = KeptFiles(request.RepositoryRoot, folder);
            var dropped = TrialCompile(request, compilations, test, group.ToList(), folder, kept);
            var written = Render(test, group.ToList(), folder, kept, dropped, request.Diagnostics);
            foreach (var probe in group.SelectMany(p => p.Planner.Serialize.Concat(p.Planner.Deserialize)))
            {
                if (dropped.TryGetValue(probe.Probe.Id, out var error))
                {
                    uncovered.Add(new UncoveredSite(probe.Probe.Site, group.First(p => p.Planner.Serialize.Concat(p.Planner.Deserialize).Contains(probe)).Production.Project.Id, "doesNotCompile", error));
                }
                else if (!kept.Contains(probe.Probe.File))
                {
                    probes.Add(probe.Probe);
                }
            }

            foreach (var sample in group.SelectMany(p => p.Planner.UsedSamples).Distinct().OrderBy(s => s.Name, StringComparer.Ordinal))
            {
                written[folder + "/Inputs/" + sample.Name] = File.ReadAllText(sample.Source);
            }

            files.AddRange(Changes(request.RepositoryRoot, test, folder, written, kept, changeSet));
        }

        uncovered = [.. uncovered.DistinctBy(u => u.Site).OrderBy(u => u.Project, StringComparer.Ordinal).ThenBy(u => u.Site, StringComparer.Ordinal)];
        Report(request, uncovered);
        var sites = productions.Sum(p => p.Sites.Count);
        var result = new NewtonsoftTestsResult
        {
            Targets = targets,
            Probes = [.. probes.OrderBy(p => p.TestProject, StringComparer.Ordinal).ThenBy(p => p.Id, StringComparer.Ordinal)],
            Uncovered = uncovered,
            Files = [.. files.OrderBy(f => f.Path, StringComparer.Ordinal)],
            Coverage = new ProbeCoverage
            {
                Sites = sites,
                WithEntryProbe = probes.Where(p => p.Kind == ProbeKind.Entry).Select(p => p.Site).Distinct().Count(),
                WithTypeProbe = probes.Where(p => p.Kind == ProbeKind.Type && !p.Id.Contains(".input.", StringComparison.Ordinal)).Select(p => p.Site).Distinct().Count(),
                Uncovered = new SortedDictionary<string, int>(uncovered.GroupBy(u => u.Reason).ToDictionary(g => g.Key, g => g.Count()), StringComparer.Ordinal),
            },
            Preview = changeSet.IsEmpty ? null : changeSet.Preview(),
        };
        return (result, changeSet.IsEmpty ? null : changeSet);
    }

    /// <summary>The test project for a production project: configuration, then --to, then the one test project named after or referencing it.</summary>
    private static ProbeTarget? Target(NewtonsoftTestsRequest request, ProjectInfo production, int productions)
    {
        string? chosen = null;
        var by = "name";
        if (request.TestProjects.FirstOrDefault(p => Matches(p.Key, production)).Value is { } configured)
        {
            (chosen, by) = (request.Model.Projects.FirstOrDefault(p => Matches(configured, p))?.Id, "config");
        }
        else if (request.To is not null && productions == 1)
        {
            (chosen, by) = (request.To, "option");
        }
        else
        {
            var selected = TestTargets.Select(request.Model, production, null, create: false, ".Tests");
            if (selected.Ambiguous.Count > 0)
            {
                request.Diagnostics.Report(DiagnosticCatalog.OFR3734,
                    $"{production.Id} is covered by {string.Join(", ", selected.Ambiguous)}; choose one with --to or newtonsoft.tests.projects.",
                    new DiagnosticLocation(production.Id), [KeyValuePair.Create<string, JsonNode?>("candidates", new JsonArray([.. selected.Ambiguous.Select(a => (JsonNode?)a)]))]);
                return null;
            }

            (chosen, by) = (selected.Project, selected.ByReference ? "reference" : "name");
        }

        if (chosen is null || request.Model.Projects.FirstOrDefault(p => p.Id == chosen) is not { } test)
        {
            request.Diagnostics.Report(DiagnosticCatalog.OFR3733,
                $"No test project covers {production.Id}; create one that references it, or name one with --to or newtonsoft.tests.projects.",
                new DiagnosticLocation(production.Id));
            return null;
        }

        if (TestFrameworks.Detect(test) is not { } framework)
        {
            request.Diagnostics.Report(DiagnosticCatalog.OFR3736,
                $"{test.Id} uses none of xunit, NUnit, or MSTest; no probes are generated for {production.Id}.", new DiagnosticLocation(test.Id));
            return null;
        }

        var directory = test.Id.Contains('/', StringComparison.Ordinal) ? test.Id[..test.Id.LastIndexOf('/')] + "/" : "";
        return new ProbeTarget { Production = production.Id, TestProject = test.Id, Framework = framework, By = by, Folder = directory + request.Folder };
    }

    private static bool Matches(string value, ProjectInfo project) =>
        string.Equals(value, project.Id, StringComparison.Ordinal) || string.Equals(value, project.Name, StringComparison.OrdinalIgnoreCase);

    /// <summary>The <c>--samples</c> files, each matched to the payload type it is named after (OFR3737 for the rest).</summary>
    private static List<SampleFile> Samples(NewtonsoftTestsRequest request, IReadOnlyList<ScannedProject> scanned)
    {
        if (request.Samples is null || !Directory.Exists(request.Samples))
        {
            return [];
        }

        var keys = scanned.SelectMany(s => s.Sites).Where(s => s.Site.Direction != SiteDirection.Serialize)
            .SelectMany(s => s.Payloads).Select(ProbePlanner.TypeKey).Distinct(StringComparer.Ordinal).OrderByDescending(k => k.Length).ToList();
        var samples = new List<SampleFile>();
        foreach (var path in Directory.EnumerateFiles(request.Samples).Order(StringComparer.Ordinal))
        {
            var name = Path.GetFileName(path);
            var stem = name.EndsWith(".json", StringComparison.OrdinalIgnoreCase) ? name[..^5] : null;
            var key = stem is null ? null : keys.FirstOrDefault(k => stem == k || stem.StartsWith(k + ".", StringComparison.Ordinal));
            if (key is null || !IsJson(path))
            {
                request.Diagnostics.Report(DiagnosticCatalog.OFR3737,
                    key is null ? $"{name} is not named <payload type full name>[.<label>].json for a type any reading site uses; it is not copied." : $"{name} is not JSON; it is not copied.",
                    data: [KeyValuePair.Create<string, JsonNode?>("file", name)]);
                continue;
            }

            var label = stem!.Length == key.Length ? "sample" : "sample-" + ProbePlanner.ProbeId(stem[(key.Length + 1)..]);
            samples.Add(new SampleFile(name, path, key, label));
        }

        return samples;
    }

    private static bool IsJson(string path)
    {
        try
        {
            using var document = JsonDocument.Parse(File.ReadAllText(path), new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true, MaxDepth = 4096 });
            return true;
        }
        catch (JsonException)
        {
            return false;
        }
    }

    /// <summary>
    /// Compiles the generated files into each of the test project's recorded compilations (earlier
    /// generated files replaced); a probe with an error is dropped, with every probe that reads what
    /// it writes, until the rest compiles. Returns the dropped probes with the first error.
    /// </summary>
    private static Dictionary<string, string> TrialCompile(NewtonsoftTestsRequest request, ICompilationSource compilations, ProjectInfo test,
        List<(ProbeTarget Target, ProbePlanner Planner, ScannedProject Production)> group, string folder, HashSet<string> kept)
    {
        var dropped = new Dictionary<string, string>(StringComparer.Ordinal);
        var recorded = test.CompilerCalls.Keys.Order(StringComparer.Ordinal)
            .Select(tfm => compilations.LoadForProject(test, tfm)).OfType<CSharpCompilation>().ToList();
        if (recorded.Count == 0)
        {
            return dropped;
        }

        var absolute = RepoPaths.ToAbsolute(request.RepositoryRoot, folder);
        for (var attempt = 0; attempt < 10; attempt++)
        {
            var files = Render(test, group, folder, kept, dropped, null);
            var errors = new List<(string Probe, string Message)>();
            foreach (var compilation in recorded)
            {
                var options = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions ?? CSharpParseOptions.Default;
                var trees = files.Where(f => f.Key.EndsWith(".cs", StringComparison.Ordinal))
                    .Select(f => CSharpSyntaxTree.ParseText(f.Value, options, RepoPaths.ToAbsolute(request.RepositoryRoot, f.Key), Encoding.UTF8))
                    .ToList();
                var trial = compilation
                    .RemoveSyntaxTrees(compilation.SyntaxTrees.Where(t => Path.GetFullPath(t.FilePath).StartsWith(absolute, StringComparison.Ordinal)))
                    .AddSyntaxTrees(trees);
                foreach (var error in trial.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error && d.Location.SourceTree is { } t && trees.Contains(t)))
                {
                    var method = error.Location.SourceTree!.GetRoot().FindNode(error.Location.SourceSpan).AncestorsAndSelf().OfType<MethodDeclarationSyntax>().FirstOrDefault();
                    var probe = group.SelectMany(p => p.Planner.Serialize.Concat(p.Planner.Deserialize)).FirstOrDefault(p => p.Method == method?.Identifier.Text);
                    if (probe is null)
                    {
                        throw new InvalidOperationException($"The generated probe runtime does not compile in {test.Id}: {error}");
                    }

                    errors.Add((probe.Probe.Id, error.GetMessage(System.Globalization.CultureInfo.InvariantCulture)));
                }
            }

            if (errors.Count == 0)
            {
                break;
            }

            foreach (var (probe, message) in errors.DistinctBy(e => e.Probe))
            {
                Drop(group, probe, message, dropped);
            }
        }

        foreach (var (probe, message) in dropped.Where(d => !d.Value.StartsWith("reads ", StringComparison.Ordinal)).OrderBy(d => d.Key, StringComparer.Ordinal))
        {
            request.Diagnostics.Report(DiagnosticCatalog.OFR3735, $"Probe {probe} does not compile in {test.Id} and is left out: {message}", new DiagnosticLocation(test.Id));
        }

        return dropped;
    }

    private static void Drop(List<(ProbeTarget Target, ProbePlanner Planner, ScannedProject Production)> group, string probe, string message, Dictionary<string, string> dropped)
    {
        if (!dropped.TryAdd(probe, message))
        {
            return;
        }

        foreach (var reader in group.SelectMany(p => p.Planner.Deserialize.Concat(p.Planner.Serialize)).Where(p => p.Reads == probe))
        {
            Drop(group, reader.Probe.Id, "reads " + probe + ", which does not compile", dropped);
        }
    }

    /// <summary>The generated files of a test project, by repository-relative path, without the dropped probes and the files taken over by the user.</summary>
    private static SortedDictionary<string, string> Render(ProjectInfo test, List<(ProbeTarget Target, ProbePlanner Planner, ScannedProject Production)> group,
        string folder, HashSet<string> kept, Dictionary<string, string> dropped, DiagnosticBag? diagnostics)
    {
        var ns = (test.RootNamespace ?? test.Name) + "." + CSharp6.Identifier(folder[(folder.LastIndexOf('/') + 1)..]);
        var framework = group[0].Target.Framework;
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal)
        {
            [folder + "/OfframpProbe.cs"] = Runtime("OfframpProbe", ns),
            [folder + "/OfframpObjectDump.cs"] = Runtime("OfframpObjectDump", ns),
        };
        foreach (var (_, planner, production) in group)
        {
            foreach (var (probes, suffix) in new[] { (planner.Serialize, "SerializeProbes"), (planner.Deserialize, "DeserializeProbes") })
            {
                var live = probes.Where(p => !dropped.ContainsKey(p.Probe.Id)).ToList();
                if (live.Count > 0)
                {
                    files[folder + "/" + ClassName(production.Project) + suffix + ".cs"] = TestClass(framework, ns, ClassName(production.Project) + suffix, live);
                }
            }
        }

        foreach (var path in kept.Where(files.ContainsKey).ToList())
        {
            diagnostics?.Report(DiagnosticCatalog.OFR3742, $"{path} no longer has Offramp's header; it is left as it is.", new DiagnosticLocation(test.Id, path));
            files.Remove(path);
        }

        return files;
    }

    private static string TestClass(ProbeFramework framework, string ns, string name, List<ProbeCode> probes)
    {
        var (fixture, method, category) = framework switch
        {
            ProbeFramework.Xunit => ((string?)null, "[global::Xunit.Fact]", $"[global::Xunit.Trait(\"Category\", \"{Category}\")]"),
            ProbeFramework.Nunit => ("[global::NUnit.Framework.TestFixture]", "[global::NUnit.Framework.Test]", $"[global::NUnit.Framework.Category(\"{Category}\")]"),
            _ => ("[global::Microsoft.VisualStudio.TestTools.UnitTesting.TestClass]", "[global::Microsoft.VisualStudio.TestTools.UnitTesting.TestMethod]",
                $"[global::Microsoft.VisualStudio.TestTools.UnitTesting.TestCategory(\"{Category}\")]"),
        };
        var b = new StringBuilder();
        b.Append(Header).Append(" (docs/spec/commands/newtonsoft.md) and rewritten on every\n")
         .Append("//   run. Remove this header to keep your own changes; Offramp then leaves the file alone.\n// </auto-generated>\n")
         .Append("#pragma warning disable CS0618, CS0612, CS1591, CS8600, CS8601, CS8602, CS8603, CS8604, CS8618, CS8625\n")
         .Append("namespace ").Append(ns).Append("\n{\n");
        if (fixture is not null)
        {
            b.Append("    ").Append(fixture).Append('\n');
        }

        b.Append("    public class ").Append(name).Append("\n    {\n");
        for (var i = 0; i < probes.Count; i++)
        {
            var probe = probes[i];
            b.Append(i == 0 ? "" : "\n")
             .Append("        ").Append(method).Append('\n')
             .Append("        ").Append(category).Append('\n')
             .Append("        public void ").Append(probe.Method).Append("()\n        {\n")
             .Append("            OfframpProbe.Check(").Append(CSharp6.String(probe.Probe.Id)).Append(", ").Append(probe.Body).Append(");\n")
             .Append("        }\n");
        }

        return b.Append("    }\n}\n").ToString();
    }

    private static string Runtime(string name, string ns)
    {
        using var stream = typeof(NewtonsoftTestsGenerator).Assembly.GetManifestResourceStream($"Offramp.Scaffolding.Newtonsoft.Runtime.{name}.template")
            ?? throw new InvalidOperationException($"Missing embedded template {name}.");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd().Replace("\r\n", "\n", StringComparison.Ordinal).Replace("OFFRAMP_NAMESPACE", ns, StringComparison.Ordinal);
    }

    /// <summary>Files in the generated folder (baselines aside) that no longer carry Offramp's header: the user's now.</summary>
    private static HashSet<string> KeptFiles(string root, string folder)
    {
        var absolute = RepoPaths.ToAbsolute(root, folder);
        if (!Directory.Exists(absolute))
        {
            return [];
        }

        return [.. Directory.EnumerateFiles(absolute, "*.cs", SearchOption.TopDirectoryOnly)
            .Where(f => !File.ReadAllText(f).Replace("\r\n", "\n", StringComparison.Ordinal).StartsWith(Header, StringComparison.Ordinal))
            .Select(f => folder + "/" + Path.GetFileName(f))];
    }

    /// <summary>Creates, edits, and deletes in the generated folder (baselines are never touched), and Compile items for a legacy project.</summary>
    private static List<GeneratedFile> Changes(string root, ProjectInfo test, string folder, SortedDictionary<string, string> written, HashSet<string> kept, ChangeSet changeSet)
    {
        var files = new List<GeneratedFile>();
        var absolute = RepoPaths.ToAbsolute(root, folder);
        var existing = Directory.Exists(absolute)
            ? Directory.EnumerateFiles(absolute, "*", SearchOption.TopDirectoryOnly).Concat(Directory.Exists(Path.Combine(absolute, "Inputs")) ? Directory.EnumerateFiles(Path.Combine(absolute, "Inputs")) : [])
                .Select(f => RepoPaths.ToRepositoryRelative(root, f)).ToHashSet(StringComparer.Ordinal)
            : [];
        foreach (var (path, content) in written)
        {
            if (!existing.Contains(path))
            {
                changeSet.Create(path, content);
                files.Add(new GeneratedFile(path, "create"));
                continue;
            }

            var before = File.ReadAllBytes(RepoPaths.ToAbsolute(root, path));
            var after = new UTF8Encoding(false).GetBytes(content);
            if (before.AsSpan().SequenceEqual(after))
            {
                files.Add(new GeneratedFile(path, "unchanged"));
            }
            else
            {
                changeSet.Edit(path, before, after);
                files.Add(new GeneratedFile(path, "edit"));
            }
        }

        foreach (var path in existing.Where(p => !written.ContainsKey(p)).Order(StringComparer.Ordinal))
        {
            if (kept.Contains(path))
            {
                files.Add(new GeneratedFile(path, "kept"));
            }
            else
            {
                changeSet.Delete(root, path);
                files.Add(new GeneratedFile(path, "delete"));
            }
        }

        if (!test.SdkStyle)
        {
            var project = RepoPaths.ToAbsolute(root, test.Id);
            var editor = ProjectFileEditor.Load(File.ReadAllBytes(project));
            var directory = test.Id.Contains('/', StringComparison.Ordinal) ? test.Id[..(test.Id.LastIndexOf('/') + 1)] : "";
            foreach (var file in files.Where(f => f.Path.EndsWith(".cs", StringComparison.Ordinal)))
            {
                var include = file.Path[directory.Length..];
                if (file.Action == "delete")
                {
                    editor.RemoveItems("Compile", include.Replace('/', '\\'));
                }
                else if (!editor.HasItem("Compile", include.Replace('/', '\\')))
                {
                    editor.AddCompile(include);
                }
            }

            changeSet.Edit(test.Id, File.ReadAllBytes(project), editor.Save());
        }

        return files;
    }

    private static void Report(NewtonsoftTestsRequest request, List<UncoveredSite> uncovered)
    {
        foreach (var group in uncovered.GroupBy(u => (u.Project, Input: u.Reason == "noInput")).OrderBy(g => g.Key.Project, StringComparer.Ordinal).ThenBy(g => g.Key.Input))
        {
            var first = group.First();
            var count = group.Count();
            var more = count == 1 ? "" : $" ({count} sites in the project; the first is shown.)";
            request.Diagnostics.Report(group.Key.Input ? DiagnosticCatalog.OFR3732 : DiagnosticCatalog.OFR3731,
                $"Site {first.Site} has no probe ({first.Reason}): {first.Detail}.{more}", new DiagnosticLocation(first.Project),
                [KeyValuePair.Create<string, JsonNode?>("sites", new JsonArray([.. group.Select(u => (JsonNode?)u.Site)]))]);
        }
    }

    private static string ClassName(ProjectInfo project) => CSharp6.Identifier(project.Name.Replace(".", "", StringComparison.Ordinal));

    private static bool IsTest(ProjectInfo project) => project.IsTestProject || project.Kind == ProjectKind.Test;
}

/// <summary>Which test framework a test project uses, from its packages and references.</summary>
internal static class TestFrameworks
{
    public static ProbeFramework? Detect(ProjectInfo project)
    {
        var names = project.PackageReferences.Select(p => p.Id)
            .Concat((project.PackagesConfigPackages ?? []).Select(p => p.Id))
            .Concat(project.AssemblyReferences.Select(r => r.Name))
            .Concat(project.Resolved.Values.SelectMany(r => r.Packages).Select(p => p.Id))
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        if (names.Overlaps(["xunit", "xunit.core", "xunit.v3", "xunit.v3.core"]))
        {
            return ProbeFramework.Xunit;
        }

        if (names.Overlaps(["NUnit", "nunit.framework"]))
        {
            return ProbeFramework.Nunit;
        }

        return names.Overlaps(["MSTest.TestFramework", "MSTest", "Microsoft.VisualStudio.TestPlatform.TestFramework", "Microsoft.VisualStudio.QualityTools.UnitTestFramework"])
            ? ProbeFramework.Mstest
            : null;
    }
}
